# 2. 删除

## 方式1：使用：列表.pop(下标)，删除指定位置的元素，并将删除的元素返回
nums = [10, 20, 30, 40, 50]
result = nums.pop()
print(nums)  # [10, 20, 30, 40]
print(result)  # 50

## 方式2：使用：列表.remove(值)，删除列表中第一次出现的指定值。
nums = [10, 20, 10, 40, 50]
nums.remove(10)
print(nums)  # [20, 10, 40, 50]

## 方式3：使用：列表.clear()，删除列表中所有的元素（变成一个空列表）。
nums = [10, 20, 10, 40, 50]
nums.clear()
print()  #

## 方式4：使用：del 列表[下标]，删除指定位置的元素。
nums = [10, 20, 10, 40, 50]
del nums[3]
print(nums)  # [10, 20, 10, 50]

