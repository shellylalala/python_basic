# 1. 新增

## 方式1：列表.append(元素)，在列表尾部追加一个元素。
nums = [10, 20, 30, 40]
nums.append(50)
print(nums)  # [10, 20, 30, 40, 50]

## 方法二：列表.insert(元素)，在指定下标处添加一个元素
nums = [10, 20, 30, 40]
nums.insert(2, 666)  # 从0开始的下标
print(nums)  # [10, 20, 666, 30, 40]

## 方式3：使用：列表.extend(可迭代对象)，将可迭代对象中的内容依次取出，追加到列表尾部
nums = [10, 20, 30, 40]
nums.extend("星露谷")
nums.extend(range(5, 10))
nums.extend([1, 7, 99])
print(nums)  # [10, 20, 30, 40, '星', '露', '谷', 5, 6, 7, 8, 9, 1, 7, 99]

