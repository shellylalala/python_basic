# 只能看，不能增删改
t1 = (28, 67, 21, 67, 11)
print(t1[3])  # 67
print(t1[-1])  # 11

# 元组中的元素，不可修改
t1 = (28, 67, 21, 67, 11)
# t1[0] = 100 # TypeError

# 元组中的元素，不可修改，但元组中如果存放了可变类型（列表），那可变类型中的内容仍可修改
t2 = (28, 67, 21, 67, 11, [100, 200, 300, ('你好', '星露谷')])
# t2[5] = 400 # TypeError
t2[5][2] = 400
# t2[5][3][0] = 'hello' # 这还是不可变的
print(t2)
