# max、min、len、sorted、sum
# 和列表一样

# max
t1 = (23, 11, 32, 30, 17)
result = max(t1)
print(result)  # 32

# min
t1 = (23, 11, 32, 30, 17)
result = min(t1)
print(result)  # 11

# len
t1 = (23, 11, 32, 30, 17)
result = len(t1)
print(result)  # 5

# sorted
t1 = (23, 11, 32, 30, 17)
result = sorted(t1, reverse=True)
print(result)  # [32, 30, 23, 17, 11]

# sum
t1 = (23, 11, 32, 30, 17)
result = sum(t1)
print(result)  # 113
